export type ExerciseCopy = {
  title: string;
  kind: string;
  body: string;
};

export function getExerciseCopy(
  locale: Locale,
  id: ExerciseId
): ExerciseCopy {
  return STRINGS[locale].exercises[id];
}

export function getExercises(locale: Locale) {
  const ids: ExerciseId[] = ['find', 'odd', 'track', 'wait', 'sequence'];
  return ids.map((id) => ({ id, ...STRINGS[locale].exercises[id] }));
}

export function useExercises() {
  const { locale } = useLocale();
  return getExercises(locale);
}

